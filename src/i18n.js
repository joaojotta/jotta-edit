export function translateMessage(message) {
  if (active !== 'pt-PT') return message;
  if (PT[message]) return PT[message];
  for (const [pattern, translated] of patterns) if (pattern.test(message)) {
    return message.replace(pattern, translated).replace(/enabled/g,'ativado').replace(/disabled/g,'desativado');
  }
  return message;
}
