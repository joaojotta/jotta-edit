const originalTexts = new WeakMap();
const originalAttrs = new WeakMap();
let active = 'en';
let preference = 'system';

export const tr = (english) => active === 'pt-PT' ? (PT[english] || english) : english;
export const locale = () => active;
export const languagePreference = () => preference;
export function configureLanguage(next = 'system', systemLocale = navigator.language || 'en') {
  preference = ['system','en','pt-PT'].includes(next) ? next : 'system';
  active = preference === 'system' ? (/^pt(?:-|$)/i.test(systemLocale) ? 'pt-PT' : 'en') : preference;
  document.documentElement.lang = active;
  translateDom(document.body);
  document.dispatchEvent(new Event('jotta:locale-changed'));
}
export function translateDom(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('code,pre,script,style,.monaco-editor')) continue;
    if (!originalTexts.has(node)) originalTexts.set(node, node.nodeValue);
    const en = originalTexts.get(node);
    const trimmed = en.trim();
    if (PT[trimmed]) node.nodeValue = en.replace(trimmed, tr(trimmed));
  }
  const elements = root.querySelectorAll ? [root, ...root.querySelectorAll('*')] : [];
  for (const element of elements) {
    if (!(element instanceof Element) || element.closest('.monaco-editor')) continue;
    let originals = originalAttrs.get(element);
    if (!originals) { originals = {}; originalAttrs.set(element, originals); }
    for (const attr of ['title','placeholder','aria-label']) {
      if (!(attr in originals) && element.hasAttribute(attr)) originals[attr] = element.getAttribute(attr);
      if (attr in originals) element.setAttribute(attr, tr(originals[attr]));
    }
  }
}

