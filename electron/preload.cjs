'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
contextBridge.exposeInMainWorld('slate', Object.freeze({
  formatNativeCode:params=>invoke('native-format:format',params),
  startNativeBuild:params=>invoke('native-build:start',params),
  stopNativeBuild:()=>invoke('native-build:stop'),
  writeNativeBuildInput:(value,eof)=>invoke('native-build:input',value,eof),
  resolveBuildDiagnostic:(root,file)=>invoke('native-build:diagnostic',root,file),
  onNativeBuildEvent:fn=>{const cb=(_event,value)=>fn(value);ipcRenderer.on('native-build:event',cb);return ()=>ipcRenderer.removeListener('native-build:event',cb);},
  startPreview: async params => {
    const result = await invoke('preview:start', params);
    if (result?.error) throw new Error(result.error);
    return result;
  },
  updatePreview: buffers => invoke('preview:update', buffers),
  stopPreview: () => invoke('preview:stop'),
  getWindowPrefs: () => invoke('window:prefs:get'),
  setWindowPrefs: value => invoke('window:prefs:set', value),
  restartConfirmed: () => invoke('window:restart-confirmed'),
  listFonts: () => invoke('fonts:list'),
  systemLocale: () => invoke('app:locale'),
  menuLocale: language => invoke('app:menu-locale', language),
  completePath: (params) => invoke('paths:complete', params),
  popupMenu: (label, point) => invoke('menu:popup', label, point),
  onMenuCommand: fn => { const cb = (_event, name) => fn(name); ipcRenderer.on('menu:command', cb); return () => ipcRenderer.removeListener('menu:command', cb); },
  browseFolders: (folder,options) => invoke('folder:browse',folder,options),
  selectFolder: folder => invoke('folder:select',folder),
  selectFile: file => invoke('folder:select-file',file),
  remoteInfo: file => invoke('remote:info',file),
  getRemoteActivity:()=>invoke('remote:activity-state'),
  onRemoteActivity:fn=>{const cb=(_event,snapshot)=>fn(snapshot);ipcRenderer.on('remote:activity',cb);return ()=>ipcRenderer.removeListener('remote:activity',cb);},
  dismissRemoteOperation:id=>invoke('remote:activity-dismiss',id),
  clearRemoteCompleted:()=>invoke('remote:activity-clear'),
  reconnectRemoteFolder:root=>invoke('remote:reconnect',root),
  onRemoteHostKey: fn => { const cb=(_event,details)=>fn(details); ipcRenderer.on('remote:host-key',cb); return ()=>ipcRenderer.removeListener('remote:host-key',cb); },
  answerRemoteHostKey: (id,accepted) => invoke('remote:host-key-answer',id,accepted),
  listFavourites:()=>invoke('favourites:list'),
  saveFavourite:value=>invoke('favourites:save',value),
  removeFavourite:id=>invoke('favourites:remove',id),
  deleteFavouriteCredentials:id=>invoke('favourites:delete-credentials',id),
  connectRemoteFolder:(location,credentials,options)=>invoke('remote:connect',location,credentials,options),
  cancelRemoteConnection:()=>invoke('remote:cancel'),
  scanFolder: (folder, options) => invoke('folder:scan', folder, options),
  createEntry: (root, folder, name, kind) => invoke('explorer:create', root, folder, name, kind),
  renameEntry: (root, file, name) => invoke('explorer:rename', root, file, name),
  moveEntry: (root, file, folder) => invoke('explorer:move', root, file, folder),
  deleteEntry: (root, file) => invoke('explorer:delete', root, file),
  chooseFiles: () => invoke('file:choose'),
  listHistory: file => invoke('history:list', file),
  getHistory: (file, id) => invoke('history:get', file, id),
  captureHistory: (file, text) => invoke('history:capture', file, text),
  setMenuShortcuts:value=>invoke('menu:shortcuts',value),
  readFile: (file) => invoke('file:read', file),
  statFile: file => invoke('file:stat',file),
  readMarkdownAsset:params=>invoke('markdown:asset',params),
  exportMarkdown:params=>invoke('markdown:export',params),
  chooseMarkdownExport:params=>invoke('markdown:export-destination',params),
  openMarkdownLink:url=>invoke('markdown:open-link',url),
  saveFile: (file, content, options) => invoke('file:write', file, content, options),
  saveAsDialog: (suggestion) => invoke('file:save-dialog', suggestion),
  getSession: () => invoke('session:get'),
  setSession: (value) => invoke('session:set', value),
  searchProject: (root, query) => invoke('project:search', root, query),
  complete: (params) => invoke('lsp:complete', params),
  gitStatus:folder=>invoke('git:status',folder),
  gitCompare:params=>invoke('git:compare',params),
  gitDetails:folder=>invoke('git:details',folder),
  gitAccount:()=>invoke('git:account'),
  gitOperation:params=>invoke('git:operation',params),
  cancelGit:()=>invoke('git:cancel'),
  openGitHubVerification:()=>invoke('git:verification'),
  chooseCloneParent:()=>invoke('git:clone-parent'),
  onGitEvent:fn=>{const cb=(_event,event)=>fn(event);ipcRenderer.on('git:event',cb);return ()=>ipcRenderer.removeListener('git:event',cb);},
  syncLanguage:params=>invoke('lsp:sync',params),
  closeLanguage:file=>invoke('lsp:close',file),
  languageDefinition:params=>invoke('lsp:definition',params),
  languageRename:params=>invoke('lsp:rename',params),
  listLanguageServers:()=>invoke('lsp:servers'),
  configureLanguageServers:value=>invoke('lsp:configure',value),
  onLanguageDiagnostics:fn=>{const cb=(_event,value)=>fn(value);ipcRenderer.on('lsp:diagnostics',cb);return ()=>ipcRenderer.removeListener('lsp:diagnostics',cb);},
  watchLocalFiles:value=>invoke('files:watch',value),
  onLocalFileChange:fn=>{const cb=(_event,value)=>fn(value);ipcRenderer.on('files:changed',cb);return ()=>ipcRenderer.removeListener('files:changed',cb);},
  windowAction: (action) => invoke('window:action', action),
  closeConfirmed: () => invoke('window:close-confirmed'),
  onBeforeClose: (fn) => { const cb = () => fn(); ipcRenderer.on('window:before-close', cb); return () => ipcRenderer.removeListener('window:before-close', cb); },
  rendererReady: () => ipcRenderer.send('app:renderer-ready'),
  onOpenFile: (fn) => { const cb = (_event, file) => fn(file); ipcRenderer.on('app:open-file', cb); return () => ipcRenderer.removeListener('app:open-file', cb); }
}));
